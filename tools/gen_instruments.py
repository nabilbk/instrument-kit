"""Generate the C configuration table from spec/instruments.json.

Usage: gen_instruments.py <instruments.json> <output.c>

The output is compiled into idev_core and used by both the LVGL widgets and
the Qt Quick module, so the data model is described exactly once.
"""
import json
import math
import sys

KINDS = {
    "Value": "IDEV_KIND_VALUE",
    "RoundGauge": "IDEV_KIND_ROUND_GAUGE",
    "LinearTape": "IDEV_KIND_LINEAR_TAPE",
    "AttitudeAxis": "IDEV_KIND_ATTITUDE_AXIS",
    "Annunciator": "IDEV_KIND_ANNUNCIATOR",
}
LEVELS = {"normal": "IDEV_LEVEL_NORMAL", "caution": "IDEV_LEVEL_CAUTION", "warning": "IDEV_LEVEL_WARNING"}
PALETTE_KEYS = [
    ("normal", "normal"), ("caution", "caution"), ("warning", "warning"),
    ("background", "background"), ("surface", "surface"), ("surface_raised", "surfaceRaised"),
    ("foreground", "foreground"), ("dim", "dim"), ("needle", "needle"),
    ("sky", "sky"), ("ground", "ground"), ("symbol", "symbol"),
]


class SpecError(Exception):
    pass


def num(v):
    if v is None:
        return "NAN"
    f = float(v)
    if not math.isfinite(f):
        raise SpecError(f"non-finite number {v!r}")
    return repr(f) + "f"


def cstr(s):
    if s is None:
        return "NULL"
    return json.dumps(s, ensure_ascii=False)


def colour(s, key):
    if not (isinstance(s, str) and s.startswith("#") and len(s) == 7):
        raise SpecError(f"palette.{key}: expected #RRGGBB, got {s!r}")
    return "0x" + s[1:].upper() + "u"


def validate(inst, ids):
    iid = inst.get("id")
    if not iid or not isinstance(iid, str):
        raise SpecError("instrument without id")
    if iid in ids:
        raise SpecError(f"{iid}: duplicate id")
    ids.add(iid)
    kind = inst.get("kind")
    if kind not in KINDS:
        raise SpecError(f"{iid}: unknown kind {kind!r}")
    if kind == "Annunciator":
        return
    lo, hi = float(inst["min"]), float(inst["max"])
    if not lo < hi:
        raise SpecError(f"{iid}: min must be < max")
    prev_to = None
    for z in inst.get("zones", []):
        if z["severity"] not in LEVELS:
            raise SpecError(f"{iid}: bad zone severity {z['severity']!r}")
        if not (lo <= z["from"] < z["to"] <= hi):
            raise SpecError(f"{iid}: zone {z} outside [min, max] or empty")
        if prev_to is not None and z["from"] < prev_to:
            raise SpecError(f"{iid}: zones overlap or are not sorted")
        prev_to = z["to"]
    a = inst.get("alerts", {})
    if a.get("cautionHigh") is not None and a.get("warningHigh") is not None and a["cautionHigh"] > a["warningHigh"]:
        raise SpecError(f"{iid}: cautionHigh must be <= warningHigh")
    if a.get("cautionLow") is not None and a.get("warningLow") is not None and a["cautionLow"] < a["warningLow"]:
        raise SpecError(f"{iid}: cautionLow must be >= warningLow")
    if kind == "RoundGauge":
        g = inst["gauge"]
        if not 0 < g["sweepAngle"] <= 360 or g["majorStep"] <= 0 or g.get("minorDivisions", 1) < 1:
            raise SpecError(f"{iid}: invalid gauge parameters")
    if kind == "LinearTape":
        t = inst["tape"]
        if t["visibleRange"] <= 0 or t["majorStep"] <= 0 or t["labelStep"] <= 0:
            raise SpecError(f"{iid}: invalid tape parameters")


def generate(spec):
    d = spec.get("defaults", {})
    out = [
        "/* GENERATED by tools/gen_instruments.py from spec/instruments.json - do not edit. */",
        "/* SPDX-License-Identifier: MIT */",
        "#include \"idev/instrument.h\"",
        "#include <math.h>",
        "",
    ]
    pal = spec["palette"]
    out.append("const idev_palette_t idev_palette = {")
    for ckey, jkey in PALETTE_KEYS:
        out.append(f"    .{ckey} = {colour(pal[jkey], jkey)},")
    out.append("};\n")

    ids = set()
    entries = []
    for idx, inst in enumerate(spec["instruments"]):
        validate(inst, ids)
        zones = inst.get("zones", [])
        zname = "NULL"
        if zones:
            zname = f"zones_{idx}"
            out.append(f"static const idev_zone_t {zname}[] = {{")
            for z in zones:
                out.append(f"    {{{num(z['from'])}, {num(z['to'])}, {LEVELS[z['severity']]}}},")
            out.append("};")
        a = inst.get("alerts", {})
        g = inst.get("gauge", {})
        t = inst.get("tape", {})
        at = inst.get("attitude", {})
        an = inst.get("annunciator", {})
        e = [
            "    {",
            f"        .id = {cstr(inst['id'])},",
            f"        .kind = {KINDS[inst['kind']]},",
            f"        .label = {cstr(inst.get('label', ''))},",
            f"        .unit = {cstr(inst.get('unit', ''))},",
            f"        .min = {num(inst.get('min', 0))},",
            f"        .max = {num(inst.get('max', 1))},",
            f"        .decimals = {int(inst.get('decimals', d.get('decimals', 0)))},",
            f"        .damping_ms = {num(inst.get('dampingMs', d.get('dampingMs', 0)))},",
            f"        .zones = {zname},",
            f"        .zone_count = {len(zones)},",
            "        .alerts = {"
            f"{num(a.get('cautionLow'))}, {num(a.get('warningLow'))}, "
            f"{num(a.get('cautionHigh'))}, {num(a.get('warningHigh'))}, "
            f"{num(a.get('hysteresis', d.get('hysteresis', 0)))}}},",
            "        .gauge = {"
            f"{num(g.get('startAngle', -135))}, {num(g.get('sweepAngle', 270))}, "
            f"{num(g.get('majorStep', 1))}, {int(g.get('minorDivisions', 1))}, "
            f"{num(g.get('labelScale', 1))}, {cstr(g.get('scaleCaption'))}}},",
            "        .tape = {"
            f"{num(t.get('visibleRange', 1))}, {num(t.get('majorStep', 1))}, "
            f"{int(t.get('minorDivisions', 1))}, {num(t.get('labelStep', 1))}}},",
            "        .attitude = {"
            f"{num(at.get('pitchVisibleRange', 40))}, {num(at.get('ladderStep', 5))}}},",
            f"        .annunciator = {{{num(an.get('blinkHz', 2))}}},",
            "    },",
        ]
        entries.extend(e)
    out.append("")
    out.append("const idev_instrument_cfg_t idev_cfg_table[] = {")
    out.extend(entries)
    out.append("};")
    out.append(f"const size_t idev_cfg_count = {len(spec['instruments'])};")
    return "\n".join(out) + "\n"


def main(argv):
    if len(argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    with open(argv[1], encoding="utf-8") as f:
        spec = json.load(f)
    if spec.get("format") != "idev-instruments":
        print("error: not an idev-instruments file", file=sys.stderr)
        return 1
    try:
        text = generate(spec)
    except (SpecError, KeyError, TypeError, ValueError) as exc:
        print(f"error: {argv[1]}: {exc}", file=sys.stderr)
        return 1
    with open(argv[2], "w", encoding="utf-8") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
